#!/usr/bin/env python3
"""Gemini Agent for Brand AI-Readiness Audit Marketplace.

This agent wraps the Agent Skill Marketplace (marketplace.json) with a live
Google Gemini model (gemini-3.6-flash) using the official `google-genai` SDK.

Capabilities:
  1. Dynamically discovers skills and entrypoint from marketplace.json.
  2. Executes site audits via the entrypoint skill (audit-orchestrator).
  3. Inspects individual SKILL.md guides and references.
  4. Resolves off-site corroboration by accepting external search findings.
  5. Generates concrete remediation artifacts (llms.txt, JSON-LD, robots.txt).
"""

import argparse
import json
import os
import subprocess
import sys
from typing import List, Optional
from dotenv import load_dotenv
from google import genai
from google.genai import types

load_dotenv()

ROOT = os.path.abspath(os.path.dirname(__file__))
PYTHON = sys.executable
API_KEY = os.getenv("GEMINI_API_KEY", "").strip("\"'")
MODEL_NAME = "gemini-3.6-flash"


def load_manifest() -> dict:
    manifest_path = os.path.join(ROOT, "marketplace.json")
    if not os.path.exists(manifest_path):
        raise FileNotFoundError(f"marketplace.json not found at {manifest_path}")
    with open(manifest_path, "r", encoding="utf-8") as f:
        return json.load(f)


MANIFEST = load_manifest()


# ---------------------------------------------------------------- Functions / Tools for Gemini

def run_site_audit(url: str, max_pages: int = 20, workdir: Optional[str] = None) -> str:
    """Run an AI-readiness and on-site engagement audit on a website URL.

    Args:
        url: The website URL to audit (e.g., 'https://neemans.com').
        max_pages: Number of pages to crawl (default 20, max 50 for quick audits).
        workdir: Directory to store the audit snapshot and report. If None, auto-derived.

    Returns:
        A JSON string containing the audit summary, total findings, and detected defects.
    """
    if not workdir:
        clean_name = url.replace("https://", "").replace("http://", "").replace("www.", "").strip("/").replace("/", "_")
        workdir = os.path.join(ROOT, f"audit-{clean_name}")

    os.makedirs(workdir, exist_ok=True)
    entrypoint_script = os.path.join(ROOT, "skills", "audit-orchestrator", "scripts", "run_audit.py")

    cmd = [
        PYTHON,
        entrypoint_script,
        "--url", url,
        "--workdir", workdir,
        "--max-pages", str(max_pages),
        "--no-render",
        "--markdown",
    ]

    print(f"\n[Agent Tool] Running audit against {url} -> {workdir}...")
    proc = subprocess.run(cmd, capture_output=True, text=True)

    report_file = os.path.join(workdir, "audit-report.json")
    if not os.path.exists(report_file):
        return json.dumps({
            "status": "error",
            "message": "Audit pipeline failed to produce audit-report.json",
            "stderr": proc.stderr[-1000:],
        })

    with open(report_file, "r", encoding="utf-8") as fh:
        report = json.load(fh)

    # Auto-generate the full elite remediation package
    try:
        rem_paths = build_remediation_package(workdir)
        rem_names = sorted(list(rem_paths.keys()))
    except Exception as exc:
        rem_names = [f"Remediation error: {exc}"]

    # Return key executive summary and findings
    condensed = {
        "status": "success",
        "workdir": workdir,
        "site": report.get("site"),
        "audited_at": report.get("audited_at"),
        "audit_meta": report.get("audit_meta"),
        "summary": report.get("summary"),
        "findings": report.get("findings"),
        "not_applicable_count": len(report.get("not_applicable", [])),
        "inconclusive": report.get("inconclusive", []),
        "remediation_artifacts": rem_names,
    }
    return json.dumps(condensed, indent=2)


def inspect_skill_guide(skill_id: str) -> str:
    """Read the SKILL.md specification and instructions for a specific skill in the marketplace.

    Args:
        skill_id: The ID of the skill (e.g., 'structured-data', 'answer-extractability', 'machine-readability').

    Returns:
        The text content of the skill's SKILL.md guide.
    """
    skill_entry = next((s for s in MANIFEST.get("skills", []) if s["id"] == skill_id), None)
    if not skill_entry:
        available = [s["id"] for s in MANIFEST.get("skills", [])]
        return f"Error: Skill '{skill_id}' not found. Available skills: {', '.join(available)}"

    skill_md = os.path.join(ROOT, skill_entry["path"], "SKILL.md")
    if not os.path.exists(skill_md):
        return f"Error: SKILL.md not found at {skill_md}"

    with open(skill_md, "r", encoding="utf-8") as f:
        return f.read()


def get_corroboration_worklist(workdir: str) -> str:
    """Fetch the search query worklist generated by entity-corroboration for off-site brand verification.

    Args:
        workdir: The working directory of an existing audit run.

    Returns:
        JSON string containing the extracted canonical claims and 4 formulation search queries.
    """
    targets_path = os.path.join(workdir, "corroboration_targets.json")
    if not os.path.exists(targets_path):
        return f"Error: corroboration_targets.json not found in {workdir}. Run run_site_audit first."

    with open(targets_path, "r", encoding="utf-8") as f:
        return f.read()


def submit_search_corroboration(workdir: str, found_urls: List[str]) -> str:
    """Submit independent third-party URLs to resolve the EC-SINGLE-SOURCE-CLAIMS check.

    Args:
        workdir: The working directory of an existing audit run.
        found_urls: List of external third-party URLs that genuinely corroborate this brand.

    Returns:
        A status message indicating whether the off-site corroboration check now passes.
    """
    results_file = os.path.join(workdir, "search_results.json")
    with open(results_file, "w", encoding="utf-8") as f:
        json.dump({"urls": found_urls}, f, indent=2)

    # Re-run entity-corroboration with the search results
    env = os.environ.copy()
    env["AUDIT_SEARCH_RESULTS"] = results_file
    analyze_script = os.path.join(ROOT, "skills", "entity-corroboration", "scripts", "analyze.py")

    proc = subprocess.run([PYTHON, analyze_script, "--workdir", workdir], env=env, capture_output=True, text=True)
    if proc.returncode != 0:
        return f"Error re-running entity-corroboration: {proc.stderr[-500:]}"

    # Re-compose report
    compose_script = os.path.join(ROOT, "skills", "audit-orchestrator", "scripts", "compose_report.py")
    out_file = os.path.join(workdir, "audit-report.json")
    subprocess.run([PYTHON, compose_script, "--workdir", workdir, "--out", out_file], capture_output=True)

    with open(out_file, "r", encoding="utf-8") as f:
        rep = json.load(f)

    # Check findings
    claims_finding = next((f for f in rep.get("findings", []) if f["check_id"] == "EC-SINGLE-SOURCE-CLAIMS"), None)
    if claims_finding:
        return f"Corroboration evaluated: Still FAILED with {claims_finding['severity']} severity ({claims_finding['evidence']})."
    return f"Corroboration evaluated: PASSED! EC-SINGLE-SOURCE-CLAIMS cleared."


from lib.remediation import build_remediation_package


def generate_remediation_suite(workdir: str) -> str:
    """Generate the full elite remediation package (RAG rewrites, Knowledge Graph hero tag, merchant schema, citation anchors, and constraint matrix).

    Args:
        workdir: The working directory of an existing audit run.

    Returns:
        A formatted status string listing all generated remediation files in workdir/remediation/.
    """
    try:
        paths = build_remediation_package(workdir)
        lines = [f"Successfully generated {len(paths)} elite remediation artifacts in {workdir}/remediation/:"]
        for name in sorted(paths):
            lines.append(f"  • {name}")
        return "\n".join(lines)
    except Exception as e:
        return f"Error generating remediation suite: {str(e)}"


def save_remediation_file(workdir: str, filename: str, content: str) -> str:
    """Save an actionable fix or code artifact (such as llms.txt or schema.jsonld) to the audit's remediation directory.

    Args:
        workdir: The audit working directory.
        filename: Name of the file (e.g. 'llms.txt', 'organization.jsonld', 'robots.txt').
        content: The text/code content of the file.

    Returns:
        The path of the created remediation file.
    """
    rem_dir = os.path.join(workdir, "remediation")
    os.makedirs(rem_dir, exist_ok=True)
    file_path = os.path.join(rem_dir, filename)
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(content)
    return f"Saved remediation artifact: {file_path}"


# ---------------------------------------------------------------- Agent Initialization

SYSTEM_INSTRUCTION = f"""You are the Lead Brand AI-Readiness & On-Site Engagement Auditor.
You are powered by Google Gemini and backed by the Brand AI-Readiness Agent Skill Marketplace.

Marketplace Overview:
{json.dumps(MANIFEST, indent=2)}

Your Mission:
1. When asked to audit a website, use the `run_site_audit` tool to execute the marketplace entrypoint.
2. Analyze the structured findings:
   - Identify why the brand is invisible or unquotable in AI assistants (discoverability).
   - Identify why human visitors referred by AI bounce upon arrival (engagement).
3. If off-site corroboration is inconclusive, inspect `get_corroboration_worklist` and use your knowledge or provided search URLs with `submit_search_corroboration`.
4. Be deeply practical: provide production-grade, mechanism-sound code and copy remediations using `generate_remediation_suite` and `save_remediation_file`:
   - Natural noun-anchored passage rewrites eliminating dangling pronouns (`1_rag_passage_rewrites.md`).
   - The 1-sentence Knowledge Graph hero tag for `AE-NO-DEFINITION` (`2_brand_definition_anchor.html`).
   - Dynamic Merchant Transparency JSON-LD schema with return policy, shipping, and price validity (`3_merchant_transparency.jsonld`).
   - Deep-link heading citation script (`4_citation_anchor_patch.js`).
   - Multi-constraint decision table for Appendix E personalization (`5_persona_constraint_matrix.html`).
   - Standard `/llms.txt` and optimized `robots.txt`.
5. Communicate with executive clarity: highlight total findings, severity distribution (Critical, High, Medium, Low), causal mechanisms, and prioritized next steps.
"""


def build_client() -> genai.Client:
    if not API_KEY:
        sys.stderr.write("ERROR: GEMINI_API_KEY is not set. Please add it to your .env file.\n")
        sys.exit(1)
    return genai.Client(api_key=API_KEY)


def main():
    parser = argparse.ArgumentParser(description="Autonomous Gemini Agent for Brand AI-Readiness Audit Marketplace.")
    parser.add_argument("--url", help="Direct URL to audit (e.g. https://neemans.com)")
    parser.add_argument("--max-pages", type=int, default=15, help="Max pages to crawl")
    parser.add_argument("query", nargs="*", help="Optional conversational prompt for the agent")
    args = parser.parse_args()

    client = build_client()

    tools = [
        run_site_audit,
        inspect_skill_guide,
        get_corroboration_worklist,
        submit_search_corroboration,
        generate_remediation_suite,
        save_remediation_file,
    ]

    config = types.GenerateContentConfig(
        system_instruction=SYSTEM_INSTRUCTION,
        tools=tools,
        temperature=0.2,
    )

    chat = client.chats.create(
        model=MODEL_NAME,
        config=config,
    )

    print("=" * 70)
    print("  BRAND AI-READINESS AUDIT — GEMINI AGENT")
    print(f"  Model: {MODEL_NAME} | Marketplace: {MANIFEST['name']} (v{MANIFEST['version']})")
    print("=" * 70)

    # Initial prompt handling
    initial_prompt = " ".join(args.query).strip() if args.query else ""
    if args.url:
        initial_prompt = f"Please audit the website {args.url} (crawling up to {args.max_pages} pages). Analyze the key findings and generate recommended remediation fixes."

    if initial_prompt:
        print(f"\nUser: {initial_prompt}\n")
        response = chat.send_message(initial_prompt)
        print(f"\nGemini Agent:\n{response.text}\n")

    # Interactive Loop if no direct URL was provided or to continue conversation
    if not args.url:
        while True:
            try:
                user_input = input("\nYou > ").strip()
                if not user_input:
                    continue
                if user_input.lower() in ("exit", "quit", "q"):
                    print("Exiting agent session. Goodbye!")
                    break

                response = chat.send_message(user_input)
                print(f"\nGemini Agent:\n{response.text}\n")
            except (KeyboardInterrupt, EOFError):
                print("\nSession ended.")
                break


if __name__ == "__main__":
    main()
